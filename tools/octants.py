#!/usr/bin/env python3
"""Writes src/octants.rs: the character for each 2x4 pattern of filled
squares. Needs Python 3.14+ (Unicode 16). Run from the repo root."""
import unicodedata

table = {}
for cp in range(0x1CD00, 0x1CDE6):
    bits = 0
    for d in unicodedata.name(chr(cp)).split("-")[1]:
        bits |= 1 << (int(d) - 1)
    table[bits] = cp

# The patterns that already existed before the octants were added.
older = {
    "": 0x20, "12345678": 0x2588,
    "1": 0x1CEA8, "2": 0x1CEAB, "7": 0x1CEA3, "8": 0x1CEA0,
    "12": 0x1FB82, "123456": 0x1FB85, "78": 0x2582, "345678": 0x2586,
    "35": 0x1FBE6, "46": 0x1FBE7,
    "13": 0x2598, "24": 0x259D, "57": 0x2596, "68": 0x2597,
    "1357": 0x258C, "2468": 0x2590, "1234": 0x2580, "5678": 0x2584,
    "2457": 0x259E, "1368": 0x259A,
    "123457": 0x259B, "123468": 0x259C, "135678": 0x2599, "245678": 0x259F,
}
for cells, cp in older.items():
    bits = sum(1 << (int(d) - 1) for d in cells)
    assert bits not in table
    table[bits] = cp
assert len(table) == 256

with open("src/octants.rs", "w") as f:
    f.write("//! Generated by tools/octants.py. Do not edit.\n//!\n")
    f.write("//! The character that fills each pattern of a cell cut 2 across by 4 down.\n")
    f.write("//! Bit 0 is the top left square, bit 1 the top right, and so on down.\n\n")
    f.write("pub const OCTANTS: [char; 256] = [\n")
    for i in range(0, 256, 8):
        f.write("    " + " ".join(f"'\\u{{{table[b]:X}}}'," for b in range(i, i + 8)) + "\n")
    f.write("];\n")
