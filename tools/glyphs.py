# Regenerates src/glyphs.rs. Run from the repo root: python3 tools/glyphs.py
# Measures each printable ASCII glyph's ink in a 2x3 grid of overlapping
# circles (the same six zones the renderer samples), averaged over fonts.
import subprocess, numpy as np
from PIL import Image, ImageDraw, ImageFont
fonts = []
for fam in ["DejaVu Sans Mono", "MesloLGS Nerd Font Mono", "Noto Sans Mono", "Liberation Mono", "CommitMonoV143"]:
    p = subprocess.run(["fc-match", "-f", "%{file}", fam + ":style=Regular"], capture_output=True, text=True).stdout
    fonts.append(p)
print(fonts)
W, H = 60, 120
# zone centres (x, y) in cell fractions and radius (fraction of width)
ZONES = [(0.27, 0.19), (0.73, 0.19), (0.27, 0.5), (0.73, 0.5), (0.27, 0.81), (0.73, 0.81)]
R = 0.30
yy, xx = np.mgrid[0:H, 0:W]
masks = [(((xx + .5) / W - cx) ** 2 + (((yy + .5) / H - cy) * 2) ** 2) < R * R for cx, cy in ZONES]
chars = [chr(c) for c in range(33, 127)]
acc = np.zeros((len(chars), 6))
for f in fonts:
    size = 10
    while True:
        font = ImageFont.truetype(f, size + 1)
        if font.getlength("M") > W: break
        size += 1
    font = ImageFont.truetype(f, size)
    asc, desc = font.getmetrics()
    y0 = (H - (asc + desc)) / 2
    for i, ch in enumerate(chars):
        im = Image.new("L", (W, H), 0)
        ImageDraw.Draw(im).text((0, y0), ch, 255, font=font)
        a = np.asarray(im) / 255.0
        acc[i] += [a[m].mean() for m in masks]
acc /= len(fonts)
acc /= acc.max(axis=0)
out = ["//! Generated by measuring real monospace fonts: how much ink each ASCII",
       "//! character puts in six zones of its cell (2 across, 3 down), 0..1.",
       "//! The renderer picks the character whose ink best matches the picture.", "",
       "#[allow(clippy::approx_constant)] // measurements, not maths",
       "pub const GLYPHS: [(char, [f32; 6]); %d] = [" % len(chars)]
for ch, v in zip(chars, acc):
    lit = "'\\''" if ch == "'" else "'\\\\'" if ch == "\\" else "'%s'" % ch
    out.append("    (%s, [%s])," % (lit, ", ".join("%.3f" % x for x in v)))
out.append("];")
open("src/glyphs.rs", "w").write("\n".join(out) + "\n")
